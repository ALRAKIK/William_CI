        integer, intent(in) :: lo_,hi_,q_,r_,s_,k1_,k2_,k3_
        real(dp) :: v_(hi_-lo_+1)
        integer :: ic_
        ic_ = gidx(k1_,k2_,k3_)
        if (ic_ > 0) then
          v_ = g(lo_:hi_,q_,r_,s_,ic_)
        else
          v_ = (g(lo_:hi_,q_,r_,s_,-ic_))
        end if
      end function gv1
