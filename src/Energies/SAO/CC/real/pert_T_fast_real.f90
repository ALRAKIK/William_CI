              if (isO(m,kn) .and. isV(z,kz)) Tv(m,z) = t1(m,z,kz)
            end do
          end do
          call dgemm('N','T', no*nx*no*ny, no*nz, 1, one, Gv, no*nx*no*ny, Tv, no*nz, zero, Vb, no*nx*no*ny)
          ext = [no, nx, no, ny, no, nz]
          sc  = [1, no, no*nx, no*nx*no, no*nx*no*ny, no*nx*no*ny*no]
          do io_=1,nord
            if (.not.hdone(io_) .and. any(use_key(:,io_)==ikey)) then
              H(:,:,:,:,:,:,io_) = 0.0_dp ; hdone(io_) = .true.
            end if
          end do
          call scatter(Vb, ext, sc, [4,1,5,2,6,3], 0.5_dp, H, ikey, use_key, nord, nw)
        end if

      end subroutine raw_block

      !-----------------------------------------------------------------!
      ! [Nov 2026] W(:,io) += A - B for every (s,io) using block ikey,    !
      ! A and B hold the same 6 slots in different index orders (codes  !
      ! as in scatter). One pass over W instead of two.                 !
      !-----------------------------------------------------------------!
      subroutine scatter2(Ain, exta, sca, codea, Bin, extb, scb, codeb, W, ikey, use_key, nord, nw, wdone)
        real(dp), intent(in)    :: Ain(*), Bin(*)
        integer     , intent(in)    :: exta(6), sca(6), codea(6), extb(6), scb(6), codeb(6)
        integer     , intent(in)    :: ikey, nord, use_key(6,6), nw(6)
        real(dp), intent(inout) :: W(*)
        logical     , intent(inout) :: wdone(6)
        integer :: s, io, ic, q, e6(6), sa6(6), sb6(6), sw6(6), qc, ordq(6), nq
        integer(8) :: off
        sw6(1) = 1
        do q=2,6
          sw6(q) = sw6(q-1)*nw(q-1)
        end do
        do io=1,nord
          do s=1,6
            if (use_key(s,io) /= ikey) cycle
            do ic=1,6
              q = slot_pos(codea(ic), s)
              e6(q) = exta(ic) ; sa6(q) = sca(ic)
              q = slot_pos(codeb(ic), s)
              sb6(q) = scb(ic)
            end do
            off = int(io-1,8)*int(sw6(6),8)*int(nw(6),8)
            qc = 1
            do q=1,6
              if (sa6(q)==1) qc = q
            end do
            ordq(1) = 1; nq = 1
            if (qc /= 1) then
              nq = 2; ordq(2) = qc
            end if
            do q=2,6
              if (q /= qc) then
                nq = nq+1; ordq(nq) = q
              end if
            end do
            call padd2(W, off, Ain, Bin, e6(ordq), sw6(ordq), sa6(ordq), sb6(ordq), .not.wdone(io))
            wdone(io) = .true.
          end do
        end do
      end subroutine scatter2

      integer function slot_pos(code, s)
        integer, intent(in) :: code, s
        if (code <= 3) then
          slot_pos = sg(code,s)
        else
          slot_pos = 3 + sg(code-3,s)
        end if
      end function slot_pos

      ! W(off + sum_q i_q*sw(q)) += A(sum i_q*sa(q)) - B(sum i_q*sb(q)), loop 1 innermost
      subroutine padd2(W, off, Ain, Bin, e, sw, sa, sb, assign)
        real(dp), intent(inout) :: W(*)
        real(dp), intent(in)    :: Ain(*), Bin(*)
        integer(8)  , intent(in)    :: off
        integer     , intent(in)    :: e(6), sw(6), sa(6), sb(6)
        logical     , intent(in)    :: assign
        integer :: i1,i2,i3,i4,i5,i6
        integer(8) :: w2,w3,w4,w5,w6
        integer :: a2,a3,a4,a5,a6, b2,b3,b4,b5,b6
        do i6=0,e(6)-1
          w6 = off + int(i6,8)*sw(6); a6 = i6*sa(6); b6 = i6*sb(6)
          do i5=0,e(5)-1
            w5 = w6 + i5*sw(5); a5 = a6 + i5*sa(5); b5 = b6 + i5*sb(5)
            do i4=0,e(4)-1
              w4 = w5 + i4*sw(4); a4 = a5 + i4*sa(4); b4 = b5 + i4*sb(4)
              do i3=0,e(3)-1
                w3 = w4 + i3*sw(3); a3 = a4 + i3*sa(3); b3 = b4 + i3*sb(3)
                do i2=0,e(2)-1
                  w2 = w3 + i2*sw(2); a2 = a3 + i2*sa(2); b2 = b3 + i2*sb(2)
                  if (assign) then
                    do i1=0,e(1)-1
                      W(w2+i1*sw(1)+1) = Ain(a2+i1*sa(1)+1) - Bin(b2+i1*sb(1)+1)
                    end do
                  else
                    do i1=0,e(1)-1
                      W(w2+i1*sw(1)+1) = W(w2+i1*sw(1)+1) + Ain(a2+i1*sa(1)+1) - Bin(b2+i1*sb(1)+1)
                    end do
                  end if
                end do
              end do
            end do
          end do
        end do
      end subroutine padd2

      !-----------------------------------------------------------------!
      ! add alpha*C to W(:,io) for every (s,io) using block ikey.        !
      ! code(c) of C index c: 1..3 virtual slot, 4..6 occupied slot;    !
      ! slot p goes to position s(p) (virtual) / 3+s(p) (occupied)      !
      !-----------------------------------------------------------------!
      subroutine scatter(Cin, ext, sc, code, alpha, W, ikey, use_key, nord, nw)
        real(dp), intent(in)    :: Cin(*)
        integer     , intent(in)    :: ext(6), sc(6), code(6), ikey, nord, use_key(6,6), nw(6)
        real(dp), intent(in)    :: alpha
        real(dp), intent(inout) :: W(*)
        integer :: s, io, ic, q, e6(6), sc6(6), sw6(6), qc, ordq(6), nq
        integer(8) :: off
        sw6(1) = 1
        do q=2,6
          sw6(q) = sw6(q-1)*nw(q-1)
        end do
        do io=1,nord
          do s=1,6
            if (use_key(s,io) /= ikey) cycle
            do ic=1,6
              if (code(ic) <= 3) then
                q = sg(code(ic),s)
              else
                q = 3 + sg(code(ic)-3,s)
              end if
              e6(q)  = ext(ic)
              sc6(q) = sc(ic)
            end do
            off = int(io-1,8)*int(sw6(6),8)*int(nw(6),8)
            ! loop order: W-contiguous index innermost, C-contiguous index next
            ! (cache-friendly 2D transpose), then the other W positions
            qc = 1
            do q=1,6
              if (sc6(q)==1) qc = q
            end do
            ordq(1) = 1; nq = 1
            if (qc /= 1) then
              nq = 2; ordq(2) = qc
            end if
            do q=2,6
              if (q /= qc) then
                nq = nq+1; ordq(nq) = q
              end if
            end do
            call padd(W, off, Cin, e6(ordq), sw6(ordq), sc6(ordq), alpha)
          end do
        end do
      end subroutine scatter

      ! W(off + sum_q i_q*sw(q)) += alpha*C(sum_q i_q*sc(q)), loop 1 innermost
      subroutine padd(W, off, Cin, e, sw, sc, alpha)
        real(dp), intent(inout) :: W(*)
        real(dp), intent(in)    :: Cin(*), alpha
        integer(8)  , intent(in)    :: off
        integer     , intent(in)    :: e(6), sw(6), sc(6)
        integer :: i1,i2,i3,i4,i5,i6
        integer(8) :: w2,w3,w4,w5,w6
        integer :: c2,c3,c4,c5,c6
        do i6=0,e(6)-1
          w6 = off + int(i6,8)*sw(6); c6 = i6*sc(6)
          do i5=0,e(5)-1
            w5 = w6 + i5*sw(5); c5 = c6 + i5*sc(5)
            do i4=0,e(4)-1
              w4 = w5 + i4*sw(4); c4 = c5 + i4*sc(4)
              do i3=0,e(3)-1
                w3 = w4 + i3*sw(3); c3 = c4 + i3*sc(3)
                do i2=0,e(2)-1
                  w2 = w3 + i2*sw(2); c2 = c3 + i2*sc(2)
                  do i1=0,e(1)-1
                    W(w2+i1*sw(1)+1) = W(w2+i1*sw(1)+1) + alpha*Cin(c2+i1*sc(1)+1)
                  end do
                end do
              end do
            end do
          end do
        end do
      end subroutine padd
      ! [Nov 2026] compact g: block (k1,k2,k3) = g(:,:,:,:,|gidx|), conjugated if gidx < 0
      real(dp) function gq(p_,q_,r_,s_,k1_,k2_,k3_)
        integer, intent(in) :: p_,q_,r_,s_,k1_,k2_,k3_
        integer :: ic_
        ic_ = gidx(k1_,k2_,k3_)
        if (ic_ > 0) then
          gq = g(p_,q_,r_,s_,ic_)
        else
          gq = (g(p_,q_,r_,s_,-ic_))
        end if
      end function gq
      ! vector g(lo:hi,q,r,s,k1,k2,k3) (first index range)
      function gv1(lo_,hi_,q_,r_,s_,k1_,k2_,k3_) result(v_)
        integer, intent(in) :: lo_,hi_,q_,r_,s_,k1_,k2_,k3_
        real(dp) :: v_(hi_-lo_+1)
        integer :: ic_
        ic_ = gidx(k1_,k2_,k3_)
        if (ic_ > 0) then
          v_ = g(lo_:hi_,q_,r_,s_,ic_)
        else
          v_ = (g(lo_:hi_,q_,r_,s_,-ic_))
        end if
      end function gv1

end subroutine build_ccsd_t_fast_r
