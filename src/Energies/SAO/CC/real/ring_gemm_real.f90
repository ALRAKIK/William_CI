      end do
      do kj=1,N_cell
        ka = ktab(ki,kj,kb)
        !$omp parallel do private(j,i,b)
        do a=v_lo,nfuc; do j=1,no; do i=1,no; do b=v_lo,nfuc
          Z(i,j,a,b,ki,kj,ka) = Z(i,j,a,b,ki,kj,ka) + RZ(b,i,j,a,kj)
