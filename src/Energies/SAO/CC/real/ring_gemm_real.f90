                       Z(i,j,a,b,ktab(1,1,ki),ktab(1,1,kj),ktab(1,1,ka)) + (RZ(b,i,j,a,kj))
        end do; end do; end do; end do
        !$omp end parallel do
      end do
    end do
  end do
