            B2(:,c,j,b,kj) = t2(:,j,b,c,km,kj,kb)
          end do; end do; end do
          !$omp end parallel do
        end do
        call dgemm('N','N', nv*no, nmc*N_cell, nmc, one , A1, nv*no, B1, nmc, one, RZ, nv*no)
