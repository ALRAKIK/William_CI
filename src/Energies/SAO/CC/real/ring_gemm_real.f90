  real(dp) , intent(in)    :: Wvoov(v_lo:nfuc,o_hi,o_hi,v_lo:nfuc,N_cell,N_cell,N_cell)
  real(dp) , intent(in)    :: Wvovo(v_lo:nfuc,o_hi,v_lo:nfuc,o_hi,N_cell,N_cell,N_cell)
  real(dp) , intent(inout) :: R2(o_hi,o_hi,v_lo:nfuc,v_lo:nfuc,N_cell,N_cell,N_cell)
  integer :: nv, no, nmc, ki, ka, kb, kj, km, kc, i, j, a, b, m, c, k, p
