  ! calls were before; on many cores the serial loops dominated)
  !$omp parallel do collapse(2)
  do ka=1,N_cell; do kj=1,N_cell
    Z(:,:,:,:,:,kj,ka) = zero
  end do; end do
  !$omp end parallel do
