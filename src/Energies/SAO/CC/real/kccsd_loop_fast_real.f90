subroutine solve_kccsd_fast_r(blk,g,ktab,t1,t2,converged, max_iter,damping,energy_tol,residual_tol,ndiis,ecorr)

      use files
      use constants_module, only: dp, dpc
      use unitcell_module , only: nfuc, N_cell
      use cc_dims       , only: o_hi, v_lo
      use k_blocks        , only: K_block
      use cc_dims         , only: nslot, gidx           ! [Nov 2026] compact g

      implicit none 

      ! input ! 

      type(K_block), intent(in)      :: blk(N_cell)
      real(dp) , intent(inout)   :: g(nfuc,nfuc,nfuc,nfuc,nslot)   ! [Nov 2026] compact g (cc_dims gidx); vvvv block holds Wvvvv during CCSD
      integer      , intent(in)      :: max_iter,ndiis
      real(dp)     , intent(in)      :: damping,energy_tol,residual_tol
      integer      , intent(in)      :: ktab(N_cell,N_cell,N_cell)

      ! output ! 

      real(dp) , intent(inout)   :: t1(nfuc,nfuc,N_cell)
      real(dp) , intent(inout)   :: t2(o_hi,o_hi,v_lo:nfuc,v_lo:nfuc,N_cell,N_cell,N_cell)
      real(dp)     , intent(out)     :: ecorr

      ! local ! 
      
      real(dp)                       :: eimag
      logical, intent(out)           :: converged
      
      real(dp), allocatable      :: wo(:,:,:,:,:,:,:)
      real(dp), allocatable      :: t1_old(:,:,:), dt1(:,:,:)
      real(dp), allocatable      :: wx(:,:,:,:,:,:,:)
      real(dp), allocatable      :: wy(:,:,:,:,:,:,:)
      real(dp), allocatable      :: r1(:,:,:)
      real(dp), allocatable      :: r2(:,:,:,:,:,:,:)
      real(dp), allocatable      :: err(:)
      real(dp), allocatable      :: x(:)   ,trial(:)
      real(dp), allocatable      :: hx(:,:),he(:,:)

      real(dp)    , allocatable      :: denom(:),coef(:)
      integer     , allocatable      :: ix(:,:),jx(:,:)

      real(dp)                   :: fo(nfuc,nfuc,N_cell),fv(nfuc,nfuc,N_cell),fx(nfuc,nfuc,N_cell)
      real(dp)                   :: lo(nfuc,nfuc,N_cell),lv(nfuc,nfuc,N_cell)
      real(dp)                   :: energy,tau
      integer                        :: n1,n2,n,p,q,iter,h,nh
      integer                        :: i,j,a,b
      integer                        :: k,ki,kj,ka,kb

      real(dp)                       :: previous,de,norm1,norm2,max1,max2
      logical                        :: ok
      ! [Nov 2026] circular DIIS history + cached error overlaps (one new row per
      ! iteration instead of nh^2 full-length dot products), OpenMP vector loops
      integer     , allocatable      :: hslot(:)
      real(dp)    , allocatable      :: Bd(:,:)
      integer                        :: s_new
      real(dp)                       :: ss1, ss2
      logical                        :: t2_clean = .false.
      if (max_iter<1.or.ndiis<0.or.damping<=0.0_dp.or.damping>1.0_dp.or.energy_tol<=0.or.residual_tol<=0) &
        error stop 'Invalid CCSD solver parameters'
      
      n1=0 
      do k=1,N_cell
        do i=1,nfuc
          do a=1,nfuc
            if (blk(k)%occupation(i)==2.and.blk(k)%occupation(a)==0) n1=n1+1
          end do
        end do
      end do

      n2=0

      do ki=1,N_cell
        do kj=1,N_cell
          do ka=1,N_cell
            kb=ktab(ki,kj,ka)
            do i=1,nfuc
                do j=1,nfuc
                  do a=1,nfuc
                    do b=1,nfuc
                      if (blk(ki)%occupation(i)/=2.or.blk(kj)%occupation(j)/=2) cycle
                      if (blk(ka)%occupation(a)/=0.or.blk(kb)%occupation(b)/=0) cycle
                      n2=n2+1
                    end do
                  end do
                end do
            end do
          end do
        end do
      end do

      n=n1+n2

      if (n1==0.or.n2==0) error stop 'CCSD solver requires occupied and virtual orbitals'

      allocate(ix(3,n1),jx(7,n2),denom(n),x(n),err(n),trial(n))

      p=0
      do k=1,N_cell
        do i=1,nfuc
          do a=1,nfuc
            if (blk(k)%occupation(i)/=2.or.blk(k)%occupation(a)/=0) cycle
            p=p+1
            ix(:,p)=[i,a,k]
            denom(p)=blk(k)%energy(i)-blk(k)%energy(a)
          end do
        end do
      end do

      q=0
      do ki=1,N_cell
        do kj=1,N_cell
          do ka=1,N_cell
            kb=ktab(ki,kj,ka)
            do i=1,nfuc
              do j=1,nfuc
                do a=1,nfuc
                  do b=1,nfuc
                    if (blk(ki)%occupation(i)/=2.or.blk(kj)%occupation(j)/=2) cycle
                    if (blk(ka)%occupation(a)/=0.or.blk(kb)%occupation(b)/=0) cycle
                    q=q+1
                    jx(:,q)=[i,j,a,b,ki,kj,ka]
                    denom(n1+q)=blk(ki)%energy(i)+blk(kj)%energy(j)-blk(ka)%energy(a)-blk(kb)%energy(b)
                  end do
                end do
              end do
            end do
          end do
        end do
      end do

      if (minval(abs(denom))<1.0e-10_dp) error stop 'CCSD near-zero denominator'

      allocate(r1,mold=t1)
      allocate(r2(o_hi,o_hi,v_lo:nfuc,v_lo:nfuc,N_cell,N_cell,N_cell))                 ! like t2
      allocate(wo(o_hi,o_hi,o_hi,o_hi,N_cell,N_cell,N_cell))                           ! Woooo
      allocate(t1_old(nfuc,nfuc,N_cell), dt1(nfuc,nfuc,N_cell))                        ! Wvvvv lives in g
      t1_old = (0.0_dp)
      allocate(wx(v_lo:nfuc,o_hi,o_hi,v_lo:nfuc,N_cell,N_cell,N_cell))                 ! Wvoov
      allocate(wy(v_lo:nfuc,o_hi,v_lo:nfuc,o_hi,N_cell,N_cell,N_cell))                 ! Wvovo
      allocate(hx(n,max(1,ndiis)),he(n,max(1,ndiis)),coef(max(1,ndiis)))
      allocate(hslot(max(1,ndiis)), Bd(max(1,ndiis),max(1,ndiis))); hslot = 0; Bd = 0.0_dp
      t2_clean = .false.

      nh=0
      converged=.false.
      previous=0.0_dp

      ! Pack and clear inactive entries, preserving only physical amplitudes.

      call pack(t1,t2,x)
      call unpack(x)


      ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !
      ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - ! 

      write(outfile,*)
      write(outfile,*) repeat('-', 94)
      write(outfile,*) "|",repeat(' ', 38),"CCSD calculation",repeat(' ', 38),"|"
      write(outfile,*) repeat('-', 94)

      write(outfile,*) repeat('-', 94)
      write(outfile,'(1x,a1,a3,1x,a1,a,a1,a,a1,a,a1,a,a1,a,a1,a,a1)') &
      "|","  #","|","   Correlation   ","|", "      dE     ","|","    Max R1   ","|", "    Max R2   ",&
      "|","    RMS R1   ","|","    RMS R2   ","|"
      write(outfile,*) repeat('-', 94)
      flush(outfile)

      write(*,*) repeat('-', 94)
      write(*,'(1x,a1,a3,1x,a1,a,a1,a,a1,a,a1,a,a1,a,a1,a,a1)') &
      "|","  #","|","   Correlation   ","|", "      dE     ","|","    Max R1   ","|", "    Max R2   ",&
      "|","    RMS R1   ","|","    RMS R2   ","|"
      write(*,*) repeat('-', 94)
      flush(6)
      ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !
      ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !

      do iter=0,max_iter

        call build_ccsd_f_h_r(blk,g,ktab,t1,t2,fo,fv,fx)
        call build_ccsd_l_h_r(blk,g,t1,fo,fv,lo,lv)
        dt1 = t1 - t1_old                                   ! Wvvvv(t1) inside g
        call update_vvvv_in_g_h_r(blk,g,ktab,dt1)
        t1_old = t1
        call build_ccsd_w_fast_r(blk,g,ktab,t1,t2,wo,wx,wy)              ! [Nov 2026] zgemm W
        call build_ccsd_residuals_fast_r(blk,g,ktab,t1,t2,fo,fv,fx,lo,lv,wo,wx,wy,r1,r2)   ! [Nov 2026] zgemm residual
        call pack(r1,r2,err)

        max1=0.0_dp; max2=0.0_dp; ss1=0.0_dp; ss2=0.0_dp
        !$omp parallel do reduction(max:max1) reduction(+:ss1)
        do p=1,n1
          max1=max(max1,abs(err(p))); ss1=ss1+abs(err(p))**2
        end do
        !$omp end parallel do
        !$omp parallel do reduction(max:max2) reduction(+:ss2)
        do p=n1+1,n
          max2=max(max2,abs(err(p))); ss2=ss2+abs(err(p))**2
        end do
        !$omp end parallel do
        norm1=sqrt(ss1/real(n1,dp))
        norm2=sqrt(ss2/real(n2,dp))

        energy=(0.0_dp)

        !$omp parallel do private(i,j,a,b,ki,kj,ka,kb,tau) reduction(+:energy)
        do q=1,n2
          i=jx(1,q); j=jx(2,q); a=jx(3,q); b=jx(4,q)
          ki=jx(5,q); kj=jx(6,q); ka=jx(7,q); kb=ktab(ki,kj,ka)
          tau=t2(i,j,a,b,ki,kj,ka)
          if (ki==ka.and.kj==kb) tau=tau+t1(i,a,ki)*t1(j,b,kj)
          energy=energy+(2.0_dp*gq(i,a,j,b,ki,ka,kj)-gq(i,b,j,a,ki,kb,kj))*tau
        end do
        !$omp end parallel do

        ecorr=real(energy,dp); eimag=0.0_dp

        de=0.0_dp


        if (iter>0) de=ecorr-previous

        ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !
        ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !
        
        write(outfile,"(1x,a1,i3,1x,a1,f16.12,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1)")      & 
        "|",iter,"|",ecorr,"|",dE,"|",max1,"|",max2,"|",norm1,"|",norm2,"|"
        write(outfile,*) repeat('-', 94)
        flush(outfile)

        write(*,"(1x,a1,i3,1x,a1,f16.12,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1,f12.8,1x,a1)")      & 
        "|",iter,"|",ecorr,"|",dE,"|",max1,"|",max2,"|",norm1,"|",norm2,"|"
        write(*,*) repeat('-', 94)
        flush(6)
        ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !
        ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - !


        if (.not.(max1<huge(1.0_dp).and.max2<huge(1.0_dp).and.abs(ecorr)<huge(1.0_dp))) &
          error stop 'CCSD nonfinite residual or energy'

        if (max(max1,max2)<residual_tol.and.(iter==0.or.abs(de)<energy_tol)) then
          converged=.true.; exit
        end if

      if (iter==max_iter) exit

      call pack(t1,t2,x)
      ! DIIS pairs CURRENT amplitudes with their CURRENT raw residuals.
      ! Extrapolate a Jacobi step from the mixed pair. With DIIS disabled
      ! this is exactly x_new=x+damping*R/D.
      if (ndiis>=2) then
        ! [Nov 2026] circular history: the oldest vector's slot is reused
        if (nh==ndiis) then
          hslot(1:ndiis-1)=hslot(2:ndiis); nh=ndiis-1
        end if
        do s_new=1,ndiis
          if (.not.any(hslot(1:nh)==s_new)) exit
        end do
        nh=nh+1; hslot(nh)=s_new
        !$omp parallel do
        do p=1,n
          hx(p,s_new)=x(p); he(p,s_new)=err(p)
        end do
        !$omp end parallel do
        do h=1,nh
          Bd(s_new,hslot(h))=rdot(he(:,s_new),he(:,hslot(h)))
          Bd(hslot(h),s_new)=Bd(s_new,hslot(h))
        end do
        if (nh>=2.and.iter>=2) then
          call diis_from_B(nh,coef(1:nh),ok)
          if (ok) then
            !$omp parallel do private(h)
            do p=1,n
              trial(p)=(0.0_dp)
              do h=1,nh
                trial(p)=trial(p)+coef(h)*(hx(p,hslot(h))+damping*he(p,hslot(h))/denom(p))
              end do
            end do
            !$omp end parallel do
          else
            call jacobi_step()
            nh=1; hslot(1)=s_new
            write(*,'(A)') 'CCSD DIIS reset: ill-conditioned subspace'
          end if
        else
          call jacobi_step()
        end if
      else
        call jacobi_step()
      end if

      previous=ecorr
      call unpack(trial)

      end do

      if (converged) then
        write(*,'(A)')
        write(*,'(A)') '*---------------------*'
        write(*,'(A)') '*-*  CCSD CONVERGED *-*'
        write(*,'(A)') '*---------------------*'
        write(*,'(A)')
      else
        write(*,'(A)')
        write(*,'(A)') '*----------------------------------------------*'
        write(*,'(A)') '   CCSD NOT CONVERGED: iteration limit reached  '
        write(*,'(A)') '*----------------------------------------------*'
        write(*,'(A)')
      end if

      ! restore the original vvvv integrals in g
      dt1 = -t1_old
      call update_vvvv_in_g_h_r(blk,g,ktab,dt1)

      deallocate(ix,jx,denom,x,err,trial,hx,he,coef,r1,r2,wo,wx,wy,t1_old,dt1,hslot,Bd)
    
contains

! [Nov 2026] trial = x + damping*err/denom (threaded)
subroutine jacobi_step()
      !$omp parallel do
      do p=1,n
        trial(p)=x(p)+damping*err(p)/denom(p)
      end do
      !$omp end parallel do
end subroutine jacobi_step

! [Nov 2026] real(sum((u)*v)) without a temporary, threaded
real(dp) function rdot(u,v)
      real(dp), intent(in) :: u(:), v(:)
      integer  :: pp
      real(dp) :: acc
      acc=0.0_dp
      !$omp parallel do reduction(+:acc)
      do pp=1,size(u)
        acc=acc+real(u(pp),dp)*real(v(pp),dp)+0.0_dp*0.0_dp
      end do
      !$omp end parallel do
      rdot=acc
end function rdot

! [Nov 2026] same solver as diis_coefficients (cc_tools.f90) on the cached
! overlaps mat(i,j) = Bd(hslot(i),hslot(j))
subroutine diis_from_B(m,c,okk)
      integer , intent(in)  :: m
      real(dp), intent(out) :: c(m)
      logical , intent(out) :: okk
      real(dp) :: mat(m+1,m+1), rhs(m+1), row(m+1), factor, scale, tmp
      integer  :: ii, jj, kk, pp
      okk=.false.; c=0.0_dp; mat=0.0_dp; rhs=0.0_dp
      do ii=1,m
        do jj=1,m
          mat(ii,jj)=Bd(hslot(ii),hslot(jj))
        end do
      end do
      scale=maxval(abs(mat(:m,:m)))
      if (scale<=tiny(1.0_dp)) return
      mat(:m,:m)=mat(:m,:m)/scale
      do ii=1,m
        mat(ii,ii)=mat(ii,ii)+1.0e-12_dp
      end do
      mat(:m,m+1)=-1.0_dp
      mat(m+1,:m)=-1.0_dp
      rhs(m+1)   =-1.0_dp
      do kk=1,m+1
        pp=kk-1+maxloc(abs(mat(kk:m+1,kk)),dim=1)
        if (abs(mat(pp,kk))<1.0e-14_dp) return
        row=mat(kk,:); mat(kk,:)=mat(pp,:); mat(pp,:)=row
        tmp=rhs(kk); rhs(kk)=rhs(pp); rhs(pp)=tmp
        do ii=kk+1,m+1
          factor=mat(ii,kk)/mat(kk,kk)
          mat(ii,kk:m+1)=mat(ii,kk:m+1)-factor*mat(kk,kk:m+1)
          rhs(ii)=rhs(ii)-factor*rhs(kk)
        end do
      end do
      do ii=m+1,1,-1
        rhs(ii)=(rhs(ii)-sum(mat(ii,ii+1:m+1)*rhs(ii+1:m+1)))/mat(ii,ii)
      end do
      c=rhs(:m)
      okk=all(abs(c)<100.0_dp).and.abs(sum(c)-1.0_dp)<1.0e-8_dp
end subroutine diis_from_B

subroutine pack(a1,a2,v)

      real(dp), intent(in)  :: a1(nfuc,nfuc,N_cell)
      real(dp), intent(in)  :: a2(o_hi,o_hi,v_lo:nfuc,v_lo:nfuc,N_cell,N_cell,N_cell)
      real(dp), intent(out) :: v(n)

      do p=1,n1
        v(p)=a1(ix(1,p),ix(2,p),ix(3,p))
      end do
      !$omp parallel do
      do q=1,n2
        v(n1+q)=a2(jx(1,q),jx(2,q),jx(3,q),jx(4,q),jx(5,q),jx(6,q),jx(7,q))
      end do
      !$omp end parallel do

end subroutine


subroutine unpack(v)

      real(dp), intent(in) :: v(n)

      t1=(0.0_dp)
      ! [Nov 2026] non-physical t2 entries are zeroed once; afterwards only the
      ! physical entries are written (nothing else writes t2 in the loop)
      if (.not.t2_clean) then
        t2=(0.0_dp); t2_clean=.true.
      end if

      do p=1,n1
        t1(ix(1,p),ix(2,p),ix(3,p))=v(p)
      end do
      !$omp parallel do
      do q=1,n2
        t2(jx(1,q),jx(2,q),jx(3,q),jx(4,q),jx(5,q),jx(6,q),jx(7,q))=v(n1+q)
      end do
      !$omp end parallel do

end subroutine

      ! [Nov 2026] compact g: block (k1,k2,k3) = g(:,:,:,:,|gidx|), conjugated if gidx < 0
      real(dp) function gq(p_,q_,r_,s_,k1_,k2_,k3_)
        integer, intent(in) :: p_,q_,r_,s_,k1_,k2_,k3_
        integer :: ic_
        ic_ = gidx(k1_,k2_,k3_)
        if (ic_ > 0) then
          gq = g(p_,q_,r_,s_,ic_)
        else
          gq = (g(p_,q_,r_,s_,-ic_))
        end if
      end function gq
      ! vector g(lo:hi,q,r,s,k1,k2,k3) (first index range)
      function gv1(lo_,hi_,q_,r_,s_,k1_,k2_,k3_) result(v_)
        integer, intent(in) :: lo_,hi_,q_,r_,s_,k1_,k2_,k3_
        real(dp) :: v_(hi_-lo_+1)
        integer :: ic_
        ic_ = gidx(k1_,k2_,k3_)
        if (ic_ > 0) then
          v_ = g(lo_:hi_,q_,r_,s_,ic_)
        else
          v_ = (g(lo_:hi_,q_,r_,s_,-ic_))
        end if
      end function gv1

end subroutine solve_kccsd_fast_r